"""Encode the bundled test clip as QuickTime Animation packets for Lua decoding.

FFmpeg and ffprobe are development tools only. The mod plays the generated
encoded packets from its ZIP without an external decoder or image sequence.
This small local test does not implement a YouTube or Twitch video decoder.
"""

from pathlib import Path
import argparse
import hashlib
import json
import re
import shutil
import struct
import subprocess
import tempfile


MOD = Path(__file__).resolve().parents[1]
SOURCE = "assets/media/test.ogv"
DATA = "scripts/media/TMSDecodedClipData.lua"
CODEC = "qtrle-rgb24"
WIDTH, HEIGHT, FPS, DURATION = 32, 18, 10, 6
FRAME_COUNT = FPS * DURATION
KEYFRAME_INTERVAL = 10
FRAME_PATTERN = re.compile(
    r'^        \{hex = "([0-9a-f]+)", keyframe = (true|false), '
    r'rgbSha256 = "([0-9a-f]{64})"\},$', re.MULTILINE)
SOURCE_HASH_PATTERN = re.compile(r'^    sourceSha256 = "([0-9a-f]{64})",$', re.MULTILINE)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def validate_packets(frames):
    """Check bounded packet headers and the intended independently seekable GOPs."""
    if len(frames) != FRAME_COUNT:
        raise ValueError(f"Expected {FRAME_COUNT} encoded video packets")
    for index, frame in enumerate(frames):
        packet = bytes.fromhex(frame["hex"])
        if not 7 <= len(packet) <= WIDTH * HEIGHT * 5 + HEIGHT * 8 + 14:
            raise ValueError(f"Invalid encoded packet size at frame {index}")
        if struct.unpack_from(">I", packet)[0] != len(packet):
            raise ValueError(f"Encoded packet length mismatch at frame {index}")
        flags = struct.unpack_from(">H", packet, 4)[0]
        if flags not in (0, 8):
            raise ValueError(f"Unexpected qtrle header flags at frame {index}")
        if flags == 8:
            if len(packet) < 15:
                raise ValueError(f"Truncated qtrle line header at frame {index}")
            start, reserved1, lines, reserved2 = struct.unpack_from(">4H", packet, 6)
            if reserved1 or reserved2 or start + lines > HEIGHT or lines == 0:
                raise ValueError(f"Invalid qtrle line range at frame {index}")
        if frame["keyframe"] != (index % KEYFRAME_INTERVAL == 0):
            raise ValueError(f"Unexpected keyframe interval at frame {index}")
        if frame["keyframe"] and flags != 0:
            raise ValueError(f"Partial qtrle keyframe at frame {index}")
        if not re.fullmatch(r"[0-9a-f]{64}", frame["rgbSha256"]):
            raise ValueError(f"Invalid decoded reference hash at frame {index}")


def render_data(source_hash, frames):
    packets = hashlib.sha256()
    references = hashlib.sha256()
    for frame in frames:
        packet = bytes.fromhex(frame["hex"])
        packets.update(struct.pack(">I", len(packet)))
        packets.update(packet)
        references.update(bytes.fromhex(frame["rgbSha256"]))
    lines = [
        "-- Generated by tools/generate_decoded_clip.py from the bundled test.ogv.",
        "-- Real qtrle RGB24 packets, decoded in Lua at runtime; no frame image files.",
        "-- rgbSha256 describes the FFmpeg-decoded top-to-bottom RGB24 reference.",
        "TMSDecodedClipData = {",
        f'    codec = "{CODEC}",',
        f"    width = {WIDTH},",
        f"    height = {HEIGHT},",
        f"    fps = {FPS},",
        f"    duration = {DURATION},",
        f"    frameCount = {FRAME_COUNT},",
        f"    keyframeInterval = {KEYFRAME_INTERVAL},",
        f'    source = "{SOURCE}",',
        f'    sourceSha256 = "{source_hash}",',
        f'    packetsSha256 = "{packets.hexdigest()}",',
        f'    rgbHashesSha256 = "{references.hexdigest()}",',
        "    frames = {",
    ]
    for frame in frames:
        keyframe = "true" if frame["keyframe"] else "false"
        lines.append(f'        {{hex = "{frame["hex"]}", keyframe = {keyframe}, '
                     f'rgbSha256 = "{frame["rgbSha256"]}"}},')
    lines.extend(["    }", "}", ""])
    return "\n".join(lines)


def parse_data(text):
    """Parse only our generated data syntax; never execute Lua during the build."""
    source_hash = SOURCE_HASH_PATTERN.search(text)
    if source_hash is None:
        raise ValueError("Missing decoded clip source hash")
    frames = [{"hex": packet, "keyframe": keyframe == "true", "rgbSha256": reference}
              for packet, keyframe, reference in FRAME_PATTERN.findall(text)]
    validate_packets(frames)
    if text != render_data(source_hash.group(1), frames):
        raise ValueError("Decoded clip packets or metadata changed; run generate_decoded_clip.py")
    return source_hash.group(1), frames


def validate_assets(mod=MOD):
    """Check source and encoded-data integrity using only the Python standard library."""
    mod = Path(mod).resolve()
    for name in (SOURCE, DATA):
        path = mod / name
        if not path.is_file() or path.is_symlink() or not path.resolve().is_relative_to(mod):
            raise ValueError(f"Missing or unsafe decoded clip asset: {name}")
    source_hash, _ = parse_data((mod / DATA).read_text(encoding="utf-8"))
    if source_hash != sha256((mod / SOURCE).read_bytes()):
        raise ValueError("Decoded clip source changed; run generate_decoded_clip.py")
    return [DATA]


def encode_frames(ffmpeg, ffprobe, source):
    """Use the official codec implementation to encode and decode the reference."""
    source_probe = json.loads(subprocess.run(
        [ffprobe, "-v", "error", "-select_streams", "v:0", "-show_streams",
         "-show_format", "-of", "json", str(source)],
        check=True, capture_output=True).stdout)
    source_stream = source_probe["streams"][0]
    source_duration = float(source_stream.get("duration", source_probe["format"]["duration"]))
    if (source_stream["width"], source_stream["height"], source_stream["r_frame_rate"]) != (
            640, 360, "30/1") or abs(source_duration - DURATION) > 0.001:
        raise ValueError("Expected the bundled 640x360, 30fps, six-second test.ogv")
    # Select source frames 0, 3, ... 177 explicitly to keep time zero aligned
    # with the unchanged native OGV player and its existing audio stream.
    video_filter = f"select=not(mod(n\\,3)),scale={WIDTH}:{HEIGHT}:flags=lanczos"
    with tempfile.TemporaryDirectory(prefix="tms_decoded_clip_") as staging_name:
        movie = Path(staging_name) / "reference.mov"
        command = [ffmpeg, "-hide_banner", "-loglevel", "error", "-threads", "1",
                   "-i", str(source), "-an", "-sn", "-dn", "-vf", video_filter,
                   "-r", str(FPS), "-frames:v", str(FRAME_COUNT), "-c:v", "qtrle",
                   "-pix_fmt", "rgb24", "-g", str(KEYFRAME_INTERVAL), str(movie)]
        subprocess.run(command, check=True, capture_output=True)
        probe = json.loads(subprocess.run(
            [ffprobe, "-v", "error", "-select_streams", "v:0", "-show_packets",
             "-show_streams", "-of", "json", str(movie)],
            check=True, capture_output=True).stdout)
        stream = probe["streams"][0]
        if (stream["codec_name"], stream["pix_fmt"], stream["width"], stream["height"],
                stream["r_frame_rate"], float(stream["duration"])) != (
                "qtrle", "rgb24", WIDTH, HEIGHT, f"{FPS}/1", DURATION):
            raise ValueError("Unexpected encoded clip format or duration")
        raw = subprocess.run(
            [ffmpeg, "-v", "error", "-i", str(movie), "-an", "-pix_fmt", "rgb24",
             "-f", "rawvideo", "pipe:1"], check=True, capture_output=True).stdout
        frame_size = WIDTH * HEIGHT * 3
        if len(raw) != frame_size * FRAME_COUNT:
            raise ValueError("Incomplete FFmpeg-decoded RGB reference")
        movie_bytes = movie.read_bytes()
        frames = []
        for index, packet in enumerate(probe["packets"]):
            if abs(float(packet["pts_time"]) - index / FPS) > 0.000001:
                raise ValueError("Encoded packet timestamp does not match the OGV clock")
            start, size = int(packet["pos"]), int(packet["size"])
            if start < 0 or size < 0 or start + size > len(movie_bytes):
                raise ValueError("Encoded packet points outside its temporary movie")
            encoded = movie_bytes[start:start + size]
            reference = raw[index * frame_size:(index + 1) * frame_size]
            frames.append({"hex": encoded.hex(), "keyframe": "K" in packet["flags"],
                           "rgbSha256": sha256(reference)})
        validate_packets(frames)
        return frames


def generate(ffmpeg, ffprobe):
    source = MOD / SOURCE
    frames = encode_frames(ffmpeg, ffprobe, source)
    destination = MOD / DATA
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(render_data(sha256(source.read_bytes()), frames),
                           encoding="utf-8", newline="\n")
    validate_assets()
    total = sum(len(frame["hex"]) // 2 for frame in frames)
    print(f"Generated {FRAME_COUNT} qtrle packets: {WIDTH}x{HEIGHT}, {FPS}fps, {DURATION}s")
    print(f"Encoded data: {total} bytes; Lua: {destination.stat().st_size} bytes")
    print(f"SHA256 source: {sha256(source.read_bytes())}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ffmpeg", default=shutil.which("ffmpeg"))
    parser.add_argument("--ffprobe", help="Defaults to ffprobe beside ffmpeg or on PATH")
    parser.add_argument("--check", action="store_true", help="Validate existing data without FFmpeg")
    args = parser.parse_args()
    if args.check:
        validate_assets()
        print(f"Decoded clip valid: {FRAME_COUNT} encoded packets, source/data hashes match")
        return
    if not args.ffmpeg:
        parser.error("FFmpeg not found; pass --ffmpeg /path/to/ffmpeg")
    sibling = Path(args.ffmpeg).with_name("ffprobe" + Path(args.ffmpeg).suffix)
    ffprobe = args.ffprobe or (str(sibling) if sibling.is_file() else shutil.which("ffprobe"))
    if not ffprobe:
        parser.error("ffprobe not found; pass --ffprobe /path/to/ffprobe")
    generate(args.ffmpeg, ffprobe)


if __name__ == "__main__":
    main()
